    private void botonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonEliminarActionPerformed
        String nombre = campoNombre.getText().trim();
        
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe digitar el nombre del ejercicio a eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            Gestora ge = new Gestora();
            List<Ejercicio> listaEjercicios = ge.cargarEjerciciosFile();
            Ejercicio ejercicioAEliminar = new Ejercicio(nombre, "", 0, "");
            List<Ejercicio> listaActual = ge.eliminarEjercicio(listaEjercicios, ejercicioAEliminar);
            ge.guardarEjerciciosFile(listaActual);
        }catch (Exception ex) {
            JOptionPane.showMessageDialog(null, "Ocurrió un error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonEliminarActionPerformed

