    private void cargarEjerciciosEnPantalla() {
        try {
            Gestora ge = new Gestora();
            List<Ejercicio> listaEjercicios = ge.cargarEjerciciosFile();
        
            if (listaEjercicios.isEmpty()) {
                campoTexto.setText("No hay ejercicios registrados en el sistema.");
            }else{
                StringBuilder contenido = new StringBuilder();
                for(Ejercicio ejer : listaEjercicios) {
                    contenido.append(ejer.toString()).append("\n----------------------------------------\n");
                }
                campoTexto.setText(contenido.toString());
            }
        }catch(Exception ex){
            JOptionPane.showMessageDialog(this, "Ocurrió un error al cargar los ejercicios: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
