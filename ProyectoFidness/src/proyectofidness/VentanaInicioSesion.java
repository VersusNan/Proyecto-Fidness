    private void botonIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonIniciarSesionActionPerformed
        String usuario = campoUsuario.getText().trim();
        String contra = campoContra.getText().trim();
    
        if(usuario.isEmpty() || contra.isEmpty()){
            JOptionPane.showMessageDialog(null, "Debe completar todos los campos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try{
            Gestora ge = new Gestora();
            List<Administrador> listaAdmins = ge.cargarAdminFile();
            if (ge.buscarAdmin(listaAdmins, usuario)) {
                JOptionPane.showMessageDialog(this, "¡Bienvenido, Administrador!");
                VentanaMenuAdministrador menuAdmin = new VentanaMenuAdministrador();
                menuAdmin.setVisible(true);
                this.dispose();
                return;
            }
            List<Cliente> listaClientes = ge.cargarClientesFile();
            if (ge.buscarCliente(listaClientes, usuario)) {
                JOptionPane.showMessageDialog(this, "¡Bienvenido al sistema Fidness!");
                VentanaMenuCliente menuCliente = new VentanaMenuCliente();
                menuCliente.setVisible(true);
                this.dispose();
                return;
            }
            JOptionPane.showMessageDialog(null, "Usuario o contraseña incorrectos.", "Error de acceso", JOptionPane.ERROR_MESSAGE);
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null, "Error al iniciar sesión: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonIniciarSesionActionPerformed

