    private void botonMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonMostrarActionPerformed
        String nombreUsuario = campoUsuario.getText().trim();
        
        if(nombreUsuario.isEmpty()){
            JOptionPane.showMessageDialog(null, "Debe digitar su usuario para buscar las rutinas.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            Gestora ge = new Gestora();
            List<Rutina> listaRutinas = ge.cargarRutinasFile();
            StringBuilder contenido = new StringBuilder();
            boolean encontradas = false;
            
            for(Rutina rut : listaRutinas){
                if(rut.getCliente().getIdUsuario().equalsIgnoreCase(nombreUsuario)){
                    contenido.append("Rutina: ").append(rut.getNombre()).append("\n");
                    contenido.append("Cliente: ").append(rut.getCliente().getNombre()).append("\n");
                    contenido.append("Ejercicios:\n");
                    if(rut.getListaE()!= null){
                        for(Ejercicio e : rut.getListaE()){
                            contenido.append(" - ").append(e.toString()).append("\n");
                        }
                    }
                    contenido.append("----------------------------------------\n");
                    encontradas = true;
                }
            }
            
            if(encontradas){
                campoTexto.setText(contenido.toString());
            }else{
                campoTexto.setText("");
                JOptionPane.showMessageDialog(null, "No se encontraron rutinas registradas para el usuario '" + nombreUsuario + "'.", "Información", JOptionPane.INFORMATION_MESSAGE);
            }
            
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null, "Ocurrió un error al buscar las rutinas: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonMostrarActionPerformed

