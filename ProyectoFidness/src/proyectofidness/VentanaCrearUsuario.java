    private void campoRolItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_campoRolItemStateChanged
        if(evt.getStateChange() == java.awt.event.ItemEvent.SELECTED){
            String seleccion = campoRol.getSelectedItem().toString();
            if (seleccion.equalsIgnoreCase("Cliente")) {
                etiquetaSegunRol.setText("Digite su nivel (Ej: Principiante):");
            } else if (seleccion.equalsIgnoreCase("Administrador")) {
                etiquetaSegunRol.setText("Digite su código:"); 
            }
        }
    }//GEN-LAST:event_campoRolItemStateChanged

