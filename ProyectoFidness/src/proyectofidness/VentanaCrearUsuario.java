    private void botonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGuardarActionPerformed
        String nombre = campoNombre.getText().trim();
        String apellidos = campoApellidos.getText().trim();
        String idUsuario = campoIdUser.getText().trim();
        String contra = campoContra.getText().trim();
        String email = campoCorreo.getText().trim();
        String rol = campoRol.getSelectedItem().toString(); 
        String txtSegunRol = campoTextoSegunRol.getText().trim(); 
    
        if (nombre.isEmpty() || apellidos.isEmpty() || idUsuario.isEmpty() || contra.isEmpty() || email.isEmpty() || txtSegunRol.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe completar todos los campos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
    
        try {
            Gestora ge = new Gestora();
            if(rol.equalsIgnoreCase("Cliente")){
                Cliente nuevoCliente = new Cliente(nombre, apellidos, idUsuario, email, contra, rol, txtSegunRol);
                List<Cliente> listaClientes = ge.cargarClientesFile();
                List<Cliente> listaActual = ge.agregarCliente(listaClientes, nuevoCliente);
                ge.guardarClientesFile(listaActual);
            }else if(rol.equalsIgnoreCase("Administrador")){
                Administrador nuevoAdmin = new Administrador(nombre, apellidos, idUsuario, email, contra, rol, txtSegunRol);
                List<Administrador> listaAdmins = ge.cargarAdminFile();
                List<Administrador> listaActual = ge.agregarAdmin(listaAdmins, nuevoAdmin);
                ge.guardarAdminFile(listaActual);
            }
            VentanaInicioSesion vNueva = new VentanaInicioSesion();
            vNueva.setVisible(true);
            this.dispose();
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null, "Ocurrió un error al registrar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonGuardarActionPerformed

