    private void botonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGuardarActionPerformed
        String nombre = campoNombre.getText().trim();
        String categoria = campoCategoria.getText().trim();
        String repeticiones = campoRepeticiones.getText().trim();
        String descripcion = campoDescripcion.getText().trim();
        
        if (nombre.isEmpty() || categoria.isEmpty() || repeticiones.isEmpty() || descripcion.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe completar todos los campos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int repeticionesN;
        try {
            repeticionesN = Integer.parseInt(repeticiones);
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(null, "Las repeticiones deben ser un número entero.", "Error de formato", JOptionPane.ERROR_MESSAGE);
            return;
        }
    
        try {
            Gestora ge = new Gestora();
            List<Ejercicio> listaEjercicios = ge.cargarEjerciciosFile();
            Ejercicio nuevoEjercicio = new Ejercicio(nombre, categoria, repeticionesN, descripcion);
            List<Ejercicio> listaActual = ge.agregarEjercicio(listaEjercicios, nuevoEjercicio);
            ge.guardarEjerciciosFile(listaActual);
            VentanaMenuAdministrador menuAdmin = new VentanaMenuAdministrador();
            menuAdmin.setVisible(true);
            this.dispose();
        }catch (Exception ex) {
        JOptionPane.showMessageDialog(null, "Ocurrió un error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonGuardarActionPerformed

