    private void botonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGuardarActionPerformed
        String nombreRutina = campoNombreRutina.getText().trim();
        String nombreUsuario = campoIdUsuario.getText().trim();
        String nombreEjercicioActual = campoNombreEjercicio.getText().trim();
        
        if(nombreRutina.isEmpty() || nombreUsuario.isEmpty()){
            JOptionPane.showMessageDialog(null, "Debe completar todos los campos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            Gestora ge = new Gestora();
            if(!nombreEjercicioActual.isEmpty()){
                List<Ejercicio> todosEjercicios = ge.cargarEjerciciosFile();
                Ejercicio encontrado = ge.buscarEjercicio(todosEjercicios, nombreEjercicioActual);
                if(encontrado != null) {
                    if(!ejerciciosRutina.contains(encontrado)) {
                        ejerciciosRutina.add(encontrado);
                    }
                }else{
                    JOptionPane.showMessageDialog(null, "El ejercicio '" + nombreEjercicioActual + "' no existe en el sistema.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            if(ejerciciosRutina.isEmpty()){
                JOptionPane.showMessageDialog(null, "Debe agregar al menos un ejercicio a la rutina.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }
            List<Cliente> clientes = ge.cargarClientesFile();
            Cliente clienteEncontrado = null;
            for(Cliente c : clientes){
                if(c.getIdUsuario() != null && c.getIdUsuario().equalsIgnoreCase(nombreUsuario)){
                    clienteEncontrado = c;
                    break;
                }
            }
            if(clienteEncontrado == null){
                JOptionPane.showMessageDialog(null, "No se encontró un cliente registrado con el usuario '" + nombreUsuario + "'", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            Rutina nuevaRutina = new Rutina(nombreRutina, clienteEncontrado, new ArrayList<>(ejerciciosRutina));
            List<Rutina> listaRutinas = ge.cargarRutinasFile();
            List<Rutina> listaActualizada = ge.agregarRutina(listaRutinas, nuevaRutina);
            ge.guardarRutinasFile(listaActualizada);

            JOptionPane.showMessageDialog(null, "¡Rutina guardada con éxito!");
            ejerciciosRutina.clear();
            VentanaMenuCliente menuCliente = new VentanaMenuCliente();
            menuCliente.setVisible(true);
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(null, "Ocurrió un error al guardar la rutina: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonGuardarActionPerformed

    private void butonAgregarOtroEjercicioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_butonAgregarOtroEjercicioActionPerformed
        String nombreEjercicio = campoNombreEjercicio.getText().trim();
        
        if(nombreEjercicio.isEmpty()){
            JOptionPane.showMessageDialog(null, "Debe digitar el nombre de un ejercicio para agregarlo.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            Gestora ge = new Gestora();
            List<Ejercicio> todosEjercicios = ge.cargarEjerciciosFile();
            Ejercicio encontrado = ge.buscarEjercicio(todosEjercicios, nombreEjercicio);
            
            if(encontrado != null){
                if(ejerciciosRutina.contains(encontrado)){
                    JOptionPane.showMessageDialog(null, "Este ejercicio ya fue agregado a la rutina", "Información", JOptionPane.INFORMATION_MESSAGE);
                }else{
                    ejerciciosRutina.add(encontrado);
                    JOptionPane.showMessageDialog(null, "¡Ejercicio agregado!\nPuede agregar otro o hacer clic en Guardar.", "Información", JOptionPane.INFORMATION_MESSAGE);
                    campoNombreEjercicio.setText("");
                }
            }else{
                JOptionPane.showMessageDialog(null, "El ejercicio '" + nombreEjercicio + "' no existe en el sistema. Agréguelo primero desde el menú de administrador o revise el nombre.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            }
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null, "Ocurrió un error al buscar el ejercicio: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_butonAgregarOtroEjercicioActionPerformed

