    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        String nombre = campoNombre.getText().trim();
   
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe digitar el nombre del ejercicio a buscar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            Gestora ge = new Gestora();
            List<Ejercicio> listaEjercicios = ge.cargarEjerciciosFile();
            Ejercicio encontrado = ge.buscarEjercicio(listaEjercicios, nombre);
            if (encontrado != null) {
                JOptionPane.showMessageDialog(null, "¡Ejercicio encontrado!\n\n" + encontrado.toString(),"Resultado de Búsqueda",JOptionPane.INFORMATION_MESSAGE);
            }else{
                JOptionPane.showMessageDialog(null,"El ejercicio '" + nombre + "' no se encuentra registrado en el sistema.","No encontrado",JOptionPane.WARNING_MESSAGE);
            }
            }catch(Exception ex) {
                JOptionPane.showMessageDialog(null, "Ocurrió un error al buscar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
    }//GEN-LAST:event_botonBuscarActionPerformed

